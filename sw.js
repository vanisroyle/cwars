self.addEventListener('install', e => {
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(FILES)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', e => {
  // Only delete this app's own caches — other apps on the same origin keep theirs.
  e.waitUntil(caches.keys().then(ks => Promise.all(ks.filter(k => k.startsWith('cwars-') && k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', e => {
  if (e.request.method !== 'GET') return;
  e.respondWith(
    caches.open(CACHE).then(c => c.match(e.request, {ignoreSearch: true})).then(hit => {
      if (hit) return hit;
      return fetch(e.request).then(r => {
        // Never cache error pages (e.g. a 503 while the host is down) — they would
        // be replayed forever, shadowing the real game.
        if (r.ok) {
          const copy = r.clone();
          caches.open(CACHE).then(cc => cc.put(e.request, copy));
        }
        return r;
      }).catch(err => {
        // Offline navigation to the root/directory URL: serve the cached index.
        if (e.request.mode === 'navigate') {
          return caches.open(CACHE).then(cc => cc.match('index.html')).then(m => m || Promise.reject(err));
        }
        throw err;
      });
    })
  );
});
